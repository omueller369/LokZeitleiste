"""Compile module-owned DE/PL/EN messages for web, backend and packaged Android.

Edit locales/modules/<module>/{de,en,pl}.json. Never edit generated bundles.
--check verifies reproducibility without modifying files.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'backend/lokzeitleiste'
LANGUAGES = ('de', 'pl', 'en')


def compile_messages():
    keyed = {lang: {} for lang in LANGUAGES}
    compat = {lang: {} for lang in LANGUAGES}
    manifest = {}
    folders = sorted((BASE / 'locales/modules').iterdir(), key=lambda p: (p.name != 'shared_legacy', p.name))
    for folder in folders:
        if not folder.is_dir():
            continue
        messages = {lang: json.loads((folder / f'{lang}.json').read_text()) for lang in LANGUAGES}
        expected = set(messages['de'])
        for lang, entries in messages.items():
            if set(entries) != expected or any(not isinstance(v, str) or not v for v in entries.values()):
                raise ValueError(f'{folder.name}/{lang}: incomplete catalogue')
            for key, value in entries.items():
                keyed[lang][folder.name + '.' + key] = value
        for key, source in messages['de'].items():
            for lang in LANGUAGES:
                compat[lang][source] = messages[lang][key]
        manifest[folder.name] = {lang: f'/locales/{folder.name}/{lang}.json' for lang in LANGUAGES}
    dump = lambda value: json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n'
    runtime = (ROOT / 'tools/localization-runtime.js').read_text()
    bundle = '/* Generated by tools/build-translations.py. */\nglobalThis.CtlMessages=' + json.dumps(keyed, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + ';\n' + runtime
    return {
        BASE / 'locales/keys.json': dump(keyed),
        BASE / 'locales/manifest.json': dump(manifest),
        BASE / 'locales/catalog.json': dump(compat),
        ROOT / 'app/src/main/assets/catalog.json': dump(compat),
        BASE / 'static/messages.js': bundle,
    }


def main():
    check = argparse.ArgumentParser()
    check.add_argument('--check', action='store_true')
    args = check.parse_args()
    for path, text in compile_messages().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Outdated generated translations: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print('Module translations complete and synchronized: Deutsch / Polski / English.')


if __name__ == '__main__':
    main()
